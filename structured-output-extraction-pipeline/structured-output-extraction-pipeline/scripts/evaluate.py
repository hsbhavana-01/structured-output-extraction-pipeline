"""Run deterministic benchmark and write a compact accuracy report."""
import json, sys
from pathlib import Path
from collections import Counter
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from extraction_pipeline.extractors import RegexInvoiceExtractor
from extraction_pipeline.pipeline import ExtractionPipeline

DATA = ROOT / "data" / "benchmark.jsonl"
REPORT = ROOT / "docs" / "accuracy_report.md"
FIELDS = ["document_type", "invoice_number", "vendor_name", "invoice_date", "currency", "total_amount"]

def normalize(v):
    if v is None: return None
    return str(v)

rows = [json.loads(line) for line in DATA.read_text(encoding="utf-8").splitlines() if line.strip()]
pipeline = ExtractionPipeline(RegexInvoiceExtractor(), max_attempts=3)
field_correct = Counter(); exact = 0; review = 0; non_invoice_correct = 0; non_invoice_total = 0
for row in rows:
    result = pipeline.run(row["text"])
    if result.status != "accepted":
        review += 1
        pred = {k: None for k in FIELDS}
    else:
        pred = result.data
    truth = row["ground_truth"]
    all_correct = True
    for field in FIELDS:
        ok = normalize(pred.get(field)) == normalize(truth.get(field))
        field_correct[field] += int(ok)
        all_correct &= ok
    exact += int(all_correct)
    if truth["document_type"] == "not_invoice":
        non_invoice_total += 1
        non_invoice_correct += int(pred.get("document_type") == "not_invoice")

field_total = len(rows)
field_accuracy = sum(field_correct.values()) / (field_total * len(FIELDS))
exact_accuracy = exact / len(rows)
non_invoice_accuracy = non_invoice_correct / non_invoice_total if non_invoice_total else 0
lines = [
    "# Accuracy Report — Synthetic Invoice Benchmark", "",
    f"**Benchmark size:** {len(rows)} samples (45 invoice-like, 15 no-target/non-invoice documents).",
    "**Extractor:** offline regex baseline; max attempts = 3.",
    "**Dataset:** deterministic synthetic examples generated by `scripts/generate_dataset.py`; see `data/benchmark.jsonl`.", "",
    "## Results", "",
    f"- **Field-level accuracy:** {field_accuracy:.1%} ({sum(field_correct.values())}/{len(rows)*len(FIELDS)} field comparisons)",
    f"- **Exact-record accuracy:** {exact_accuracy:.1%} ({exact}/{len(rows)} records have every target field correct)",
    f"- **Non-invoice classification accuracy:** {non_invoice_accuracy:.1%} ({non_invoice_correct}/{non_invoice_total})",
    f"- **Routed to review:** {review}/{len(rows)}", "",
    "| Field | Correct | Total | Accuracy |", "|---|---:|---:|---:|",
]
for field in FIELDS:
    n = field_correct[field]
    lines.append(f"| `{field}` | {n} | {len(rows)} | {n/len(rows):.1%} |")
lines += ["", "## Interpretation and limitations", "",
"This benchmark verifies the evaluation harness, empty-target handling, and baseline behavior on controlled examples. It is **not** a credible estimate of production accuracy: examples are synthetic and share predictable formats with the baseline extractor. The optional model-backed adapter has not been benchmarked here because results depend on model/version and API access. Before production, evaluate on at least 50 independently sourced and human-labeled documents, include scans/OCR noise and varied layouts, and report per-field precision/recall plus exact-match accuracy.", ""]
REPORT.write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
